#!/usr/bin/env python3
"""BLONDA AKAI — read a BLONDA Max for Live device's panel config (the CFG object in its *_ui.js: params with
[min, max, default, discrete] and the preset list) plus its params.json (panel names) and write a C++ table.

  m4l_tables.py <ui.js> <params.json> <Name> <labels.json> > tables.hpp

labels.json: {"param": ["LABEL0", "LABEL1", ...], "_short": {"param": "SHORT"}, "_skip": ["param", ...]}
for discrete values, screen names (<= 8 characters) and parameters that are panel-only (colour themes etc.).
"""
import json
import re
import sys


def js_obj_to_json(txt):
    txt = re.sub(r"//[^\n]*", "", txt)
    txt = re.sub(r"([{,]\s*)([A-Za-z_]\w*)\s*:", r'\1"\2":', txt)     # bare keys
    txt = txt.replace("'", '"')
    txt = re.sub(r",\s*([}\]])", r"\1", txt)                           # trailing commas
    return json.loads(txt)


def block(src, key, open_ch, close_ch):
    i = src.index(key)
    i = src.index(open_ch, i)
    depth, j = 0, i
    in_str = None
    while True:
        c = src[j]
        if in_str:
            if c == in_str and src[j - 1] != "\\":
                in_str = None
        elif c in "'\"":
            in_str = c
        elif c == open_ch:
            depth += 1
        elif c == close_ch:
            depth -= 1
            if depth == 0:
                return src[i:j + 1]
        j += 1


def fl(v):
    return repr(float(v)) + "f"


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ui, pjson, name, labels_path = sys.argv[1:5]
    src = open(ui, encoding="utf-8").read()
    params = js_obj_to_json(block(src, "params:", "{", "}"))
    presets = js_obj_to_json(block(src, "presets:", "[", "]"))
    keep = js_obj_to_json(block(src, "keep:", "{", "}")) if "keep:" in src else {}
    panel = [p.get("parameter_shortname") or p.get("parameter_longname") for p in json.load(open(pjson, encoding="utf-8"))]
    labels = json.load(open(labels_path, encoding="utf-8"))
    short, skip = labels.get("_short", {}), set(labels.get("_skip", []))

    ids = [k for k in params if k not in skip]
    order = list(params)                  # params.json follows the same order as CFG.params
    out = ["// Generated by Akai/tools/m4l_tables.py from the BLONDA Max for Live device's panel config. Do not edit.",
           "#pragma once", '#include "akai/instrument.hpp"', "", "namespace akai::m4l::%s {" % name, ""]
    for k in ids:
        if k in labels:
            out.append("inline const char* const kL_%s[] = {%s};" % (k, ", ".join(cstr(x) for x in labels[k])))
    out.append("")
    out.append("struct ParamDef { ParamInfo info; const char* panel; bool keep; };")
    out.append("inline const ParamDef kParams[] = {")
    for k in ids:
        p = params[k]
        lo, hi, de = p[0], p[1], p[2]
        disc = len(p) > 3 and p[3]
        steps = int(round(hi - lo)) + 1 if disc else 0
        lab = "kL_%s" % k if k in labels else "nullptr"
        pn = panel[order.index(k)] if order.index(k) < len(panel) else k
        sn = short.get(k, (pn or k).upper()[:8])
        if len(sn) > 8:
            raise SystemExit("screen name too long: %s -> %s" % (k, sn))
        out.append("    {{%s, %s, %s, %s, %s, %d, %s}, %s, %s}," % (cstr(k), cstr(sn), fl(lo), fl(hi), fl(de), steps, lab, cstr(pn or k),
                                                                     "true" if keep.get(k) else "false"))
    out.append("};")
    out.append("constexpr int kNumParams = (int)(sizeof(kParams) / sizeof(kParams[0]));")
    out.append("")
    out.append("struct PresetValue { int param; float value; };")
    out.append("struct Preset { const char* name; int n; const PresetValue* values; };")
    for i, (pname, vals) in enumerate(presets):
        pv = []
        for k, v in vals.items():
            if k in skip:
                continue
            if k not in ids:
                raise SystemExit("preset %s uses unknown param %s" % (pname, k))
            pv.append("{%d, %s}" % (ids.index(k), fl(v)))
        out.append("inline const PresetValue kP%d[] = {%s};" % (i, ", ".join(pv) if pv else "{-1, 0}"))
    out.append("inline const Preset kPresets[] = {")
    for i, (pname, vals) in enumerate(presets):
        n = len([k for k in vals if k not in skip])
        out.append("    {%s, %d, kP%d}," % (cstr(pname), n, i))
    out.append("};")
    out.append("constexpr int kNumPresets = (int)(sizeof(kPresets) / sizeof(kPresets[0]));")
    out.append("")
    out.append("} // namespace akai::m4l::%s" % name)
    sys.stdout.write("\n".join(out) + "\n")
    sys.stderr.write("%d params, %d presets\n" % (len(ids), len(presets)))


if __name__ == "__main__":
    main()
