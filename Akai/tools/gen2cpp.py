#!/usr/bin/env python3
"""BLONDA AKAI — translate a Max gen~ codebox (GenExpr) into a self-contained C++ class.

The BLONDA Max for Live devices keep all of their DSP in one gen~ codebox. GenExpr is close to C, so the
translation is mostly declarations plus a few semantic details:

  Param  name(default)          -> public double member (set from the host, like a message to gen~)
  History name(init)            -> private double state, survives between samples
  Data name(len, ch)            -> zeroed buffer owned by the class (peek/poke with gen's index rules)
  Buffer name("x")              -> external buffer the host fills (wavetables, samples)
  other assigned identifiers    -> per-sample locals (gen resets them every sample: read-before-write = 0)
  in1..inN / out1..outN         -> process(ins, outs) arguments
  samplerate, pi, twopi, ...    -> constants / members
  integer literals              -> double literals (gen has no integer division)

All arithmetic is double, like gen~. Usage:  gen2cpp.py gen.genexpr ClassName > out.hpp
"""
import re
import sys

KEYWORDS = {"if", "else", "for", "while", "return", "break", "continue"}
BUILTIN_FUNCS = {
    "wrap", "peek", "poke", "floor", "ceil", "pow", "max", "min", "clamp", "noise", "sin", "cos", "tan", "tanh",
    "abs", "exp", "sqrt", "log", "dim", "channels", "atan", "atan2", "asin", "acos", "sign", "fract", "round",
    "trunc", "fold", "mix", "scale", "mstosamps", "sampstoms", "mtof", "ftom", "dbtoa", "atodb", "fixdenorm",
    "fixnan", "exp2", "log2", "log10", "sinh", "cosh", "smoothstep", "step", "neg", "not", "bool", "int", "float",
}
CONSTANTS = {"samplerate": "sr_", "pi": "kPi", "twopi": "kTwoPi", "halfpi": "kHalfPi", "e": "kE",
             "SAMPLERATE": "sr_", "PI": "kPi", "TWOPI": "kTwoPi"}


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


def translate(src, cls):
    s = strip_comments(src)
    params, hist, datas, bufs = [], [], [], []

    def take(m, kind):
        name, args = m.group(1), m.group(2).strip()
        if kind == "Param":
            default = args.split(",")[0].strip() or "0"
            params.append((name, default))
        elif kind == "History":
            hist.append((name, args or "0"))
        elif kind == "Data":
            a = [x.strip() for x in args.split(",")]
            datas.append((name, a[0], a[1] if len(a) > 1 else "1"))
        elif kind == "Buffer":
            bufs.append((name, args.strip('"')))
        return ""

    for kind in ("Param", "History", "Data", "Buffer"):
        s = re.sub(r"\b" + kind + r"\s+([A-Za-z_]\w*)\s*\(([^)]*)\)\s*;", lambda m, k=kind: take(m, k), s)
    if re.search(r"\bDelay\s+\w+", s):
        raise SystemExit("Delay objects are not supported yet")
    if re.search(r"^\s*[A-Za-z_]\w*\s*\([^;{}]*\)\s*\{", s, re.M) and not all(
            w in KEYWORDS for w in re.findall(r"^\s*([A-Za-z_]\w*)\s*\([^;{}]*\)\s*\{", s, re.M)):
        raise SystemExit("user-defined functions are not supported yet")

    declared = {n for n, _ in params} | {n for n, _ in hist} | {n for n, *_ in datas} | {n for n, _ in bufs}
    ins = sorted({int(x) for x in re.findall(r"\bin(\d+)\b", s)})
    outs = sorted({int(x) for x in re.findall(r"\bout(\d+)\b", s)})
    nin, nout = (max(ins) if ins else 0), (max(outs) if outs else 0)

    # identifiers assigned in the body that are not declared -> per-sample locals
    assigned = set(re.findall(r"(?<![=!<>+\-*/%])\b([A-Za-z_]\w*)\s*(?:=(?!=)|\+=|-=|\*=|/=)", s))
    locals_ = sorted(a for a in assigned if a not in declared and not re.fullmatch(r"out\d+", a) and a not in KEYWORDS)

    body = s
    # numeric literals -> double literals (avoid integer division); leave identifiers like m_v0 alone
    body = re.sub(r"(?<![\w.])(\d+)(?![\w.])", r"\1.0", body)
    for k, v in CONSTANTS.items():
        body = re.sub(r"\b" + k + r"\b", v, body)
    body = re.sub(r"\bin(\d+)\b", lambda m: "in[%d]" % (int(m.group(1)) - 1), body)
    body = re.sub(r"\bout(\d+)\b", lambda m: "out[%d]" % (int(m.group(1)) - 1), body)
    # unknown function calls fail loudly instead of silently compiling against something else
    for f in set(re.findall(r"\b([A-Za-z_]\w*)\s*\(", body)):
        if f not in BUILTIN_FUNCS and f not in KEYWORDS:
            raise SystemExit("unknown gen operator: " + f)
    body = "\n".join("        " + l.rstrip() for l in body.strip().splitlines() if l.strip())

    o = []
    o.append("// Generated by Akai/tools/gen2cpp.py from a BLONDA Max for Live gen~ codebox. Do not edit by hand:")
    o.append("// change the device in Max and regenerate, so both versions stay the same sound.")
    o.append("#pragma once")
    o.append('#include "akai/genlib.hpp"')
    o.append("")
    o.append("namespace akai::gen {")
    o.append("")
    o.append("class %s {" % cls)
    o.append("public:")
    o.append("    static constexpr int kIns = %d, kOuts = %d;" % (nin, nout))
    o.append("    // parameters (messages to gen~)")
    for n, d in params:
        o.append("    double %s = %s;" % (n, d))
    for n, name in bufs:
        o.append('    Buffer %s;   // "%s", filled by the host' % (n, name))
    o.append("")
    o.append("    void prepare(double sampleRate) { sr_ = sampleRate; reset(); }")
    o.append("    void reset() {")
    for n, i in hist:
        o.append("        %s = %s;" % (n, i))
    for n, *_ in datas:
        o.append("        %s.clear();" % n)
    o.append("        rng_.seed(0x5EEDu);")
    o.append("    }")
    o.append("    void setParam(const char* name, double v);   // by gen~ parameter name")
    o.append("")
    o.append("    // one sample: in[kIns] -> out[kOuts]")
    o.append("    inline void tick(const double* in, double* out) {")
    o.append("        (void)in;")
    if locals_:
        o.append("        double " + ", ".join(l + " = 0" for l in locals_) + ";")
    o.append(body)
    o.append("    }")
    o.append("")
    o.append("private:")
    o.append("    double sr_ = 44100.0;")
    o.append("    Noise rng_;")
    o.append("    inline double noise() { return rng_.next(); }")
    for n, i in hist:
        o.append("    double %s = %s;" % (n, i))
    for n, ln, ch in datas:
        o.append("    Data %s{(int)(%s), (int)(%s)};" % (n, ln, ch))
    o.append("};")
    o.append("")
    o.append("inline void %s::setParam(const char* name, double v) {" % cls)
    for n, _ in params:
        o.append('    if (!std::strcmp(name, "%s")) { %s = v; return; }' % (n, n))
    o.append("}")
    o.append("")
    o.append("} // namespace akai::gen")
    return "\n".join(o) + "\n", [n for n, _ in params]


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    code, names = translate(open(sys.argv[1], encoding="utf-8").read(), sys.argv[2])
    sys.stdout.write(code)
    sys.stderr.write("%d params: %s\n" % (len(names), " ".join(names)))
