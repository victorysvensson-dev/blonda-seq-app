/// Dot-matrix text `height` points tall (7 rows), like setDM(el, text, h).
struct DotMatrixText: View {
    let text: String
    var height: CGFloat = 20
    var color: Color = T.fg
    var offOpacity: Double = 0.07
    var glow: Color? = nil
    var body: some View {
        let u = height / 7, w = CGFloat(DMF.units(text)) * u
        Canvas { ctx, _ in
            var x: CGFloat = 0
            var on = Path(), off = Path()
            for ch in text.uppercased() {
                let g = DMF.glyphs[ch] ?? DMF.glyphs[" "]!
                let gw = g[0].count
                for r in 0..<7 {
                    let row = Array(g[r])
                    for c in 0..<gw {
                        let lit = row[c] == "1", rad = (lit ? 0.41 : 0.3) * u
                        let cx = (x + CGFloat(c) + 0.5) * u, cy = (CGFloat(r) + 0.5) * u
                        let rect = CGRect(x: cx - rad, y: cy - rad, width: rad * 2, height: rad * 2)
                        if lit { on.addEllipse(in: rect) } else { off.addEllipse(in: rect) }
                    }
                }
                x += CGFloat(gw + 1)
            }
            ctx.fill(off, with: .color(color.opacity(offOpacity)))
            if let g = glow { ctx.addFilter(.shadow(color: g, radius: 3)) }
            ctx.fill(on, with: .color(color))
        }
        .frame(width: w, height: height)
        .accessibilityLabel(text)
    }
}
